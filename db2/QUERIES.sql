FROM RECON_RESULTS ORDER BY TXN_ID;

SELECT STATUS, COUNT(*) AS RECORD_COUNT
FROM RECON_RESULTS GROUP BY STATUS ORDER BY STATUS;

SELECT TXN_ID, ACCOUNT_ID, TRAN_AMOUNT, SETTLE_AMOUNT, STATUS, DETAILS
FROM RECON_RESULTS WHERE STATUS <> 'MATCHED' ORDER BY TXN_ID;
