-- Source-table inspection
SELECT TXN_ID, ACCOUNT_ID, AMOUNT, TXN_DATE
FROM BANK_TRANSACTION
ORDER BY TXN_ID;

SELECT TXN_ID, SETTLEMENT_AMOUNT, SETTLEMENT_DATE
FROM BANK_SETTLEMENT
ORDER BY TXN_ID;

-- Compare source keys and amounts using a full outer join where supported
-- by the target Db2 version.
SELECT
    COALESCE(T.TXN_ID, S.TXN_ID) AS TXN_ID,
    T.AMOUNT AS TRAN_AMOUNT,
    S.SETTLEMENT_AMOUNT AS SETTLE_AMOUNT,
    CASE
        WHEN T.TXN_ID IS NULL THEN 'MISSING_TRANSACTION'
        WHEN S.TXN_ID IS NULL THEN 'MISSING_SETTLEMENT'
        WHEN T.AMOUNT = S.SETTLEMENT_AMOUNT THEN 'MATCHED'
        WHEN T.AMOUNT <> S.SETTLEMENT_AMOUNT THEN 'MISMATCHED'
        ELSE 'REVIEW'
    END AS RECON_STATUS
FROM BANK_TRANSACTION T
FULL OUTER JOIN BANK_SETTLEMENT S
    ON T.TXN_ID = S.TXN_ID
ORDER BY COALESCE(T.TXN_ID, S.TXN_ID);

-- Stored reconciliation results (after the application populates the table)
SELECT STATUS, COUNT(*) AS RECORD_COUNT
FROM RECON_RESULTS
GROUP BY STATUS
ORDER BY STATUS;

SELECT TXN_ID, STATUS, REASON_CODE, TRAN_AMOUNT, SETTLE_AMOUNT
FROM RECON_RESULTS
WHERE STATUS <> 'MATCHED'
ORDER BY TXN_ID;
