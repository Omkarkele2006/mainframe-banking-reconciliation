CREATE TABLE Z73968.RECON_RESULTS
(
    RUN_ID             VARCHAR(32) NOT NULL,
    TXN_ID             CHAR(10) NOT NULL,
    TRAN_ACCOUNT_ID    CHAR(10),
    SETTLE_ACCOUNT_ID  CHAR(10),
    TRAN_AMOUNT        DECIMAL(13,2),
    SETTLE_AMOUNT      DECIMAL(13,2),
    TRAN_DATE          CHAR(8),
    SETTLE_DATE        CHAR(8),
    TRAN_STATUS        CHAR(1),
    SETTLE_STATUS      CHAR(1),
    STATUS             VARCHAR(24) NOT NULL,
    DETAILS            VARCHAR(100),
    RUN_TIMESTAMP      TIMESTAMP NOT NULL WITH DEFAULT,
    CHECK (STATUS IN (
        'MATCHED',
        'MISMATCHED',
        'MISSING_SETTLEMENT',
        'MISSING_TRANSACTION'
    )),
    PRIMARY KEY (RUN_ID, TXN_ID)
);